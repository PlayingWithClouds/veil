/**
 * Writes apps/backend/internal/schema/ordinals.go: every stored model's
 * field names and OpenSchema ordinals, inherited fields included. The Go
 * target doesn't emit ordinals, and FieldSource and Revision name fields by
 * them, so they're read from the ordinal ledger (schema/openschema.lock).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const schemaDir = 'schema';
const outFile = 'apps/backend/internal/schema/ordinals.go';

type LockOrdinal = { state: string; name: string };
type LockSpace = { kind: string; ordinals: Record<string, LockOrdinal> };

/** Reads each model's own active fields from the ledger, by model name. */
function ownFields(): Map<string, Map<string, number>> {
	const lock = JSON.parse(readFileSync(join(schemaDir, 'openschema.lock'), 'utf8'));
	const models = new Map<string, Map<string, number>>();
	for (const [key, space] of Object.entries(lock.spaces as Record<string, LockSpace>)) {
		if (space.kind !== 'model') {
			continue;
		}
		const fields = new Map<string, number>();
		for (const [ordinal, entry] of Object.entries(space.ordinals)) {
			if (entry.state === 'active') {
				fields.set(entry.name, Number(ordinal));
			}
		}
		models.set(key.replace(/^model:veil\./, ''), fields);
	}
	return models;
}

/** Finds `model Child extends Parent` in the schema files. */
function parents(): Map<string, string> {
	const result = new Map<string, string>();
	for (const file of readdirSync(schemaDir).filter((name) => name.endsWith('.schema'))) {
		const text = readFileSync(join(schemaDir, file), 'utf8');
		for (const match of text.matchAll(/^model (\w+) extends (\w+)/gm)) {
			result.set(match[1], match[2]);
		}
	}
	return result;
}

/** Finds the models that are tables: not @abstract, not @value. */
function storedModels(): Set<string> {
	const result = new Set<string>();
	for (const file of readdirSync(schemaDir).filter((name) => name.endsWith('.schema'))) {
		const text = readFileSync(join(schemaDir, file), 'utf8');
		for (const match of text.matchAll(/((?:^@[^\n]*\n)*)^model (\w+)/gm)) {
			if (!/@abstract|@value/.test(match[1])) {
				result.add(match[2]);
			}
		}
	}
	return result;
}

/** Collects a model's fields with those of every model it extends. */
function allFields(model: string, own: Map<string, Map<string, number>>, parentOf: Map<string, string>): Map<string, number> {
	const fields = new Map<string, number>();
	let current: string | undefined = model;
	while (current !== undefined) {
		for (const [name, ordinal] of own.get(current) ?? []) {
			fields.set(name, ordinal);
		}
		current = parentOf.get(current);
	}
	return fields;
}

/** Renders the Go source. */
function render(): string {
	const own = ownFields();
	const parentOf = parents();
	const lines = [
		'// Code generated by scripts/schema-ordinals.ts from schema/openschema.lock. DO NOT EDIT.',
		'',
		'package schema',
		'',
		'// FieldOrdinals maps each table to its columns and their OpenSchema',
		'// ordinals, inherited fields included.',
		'var FieldOrdinals = map[string]map[string]uint32{',
	];
	for (const model of [...storedModels()].sort()) {
		const fields = [...allFields(model, own, parentOf)].sort((a, b) => a[1] - b[1]);
		lines.push(`\t${JSON.stringify(model)}: {`);
		for (const [name, ordinal] of fields) {
			lines.push(`\t\t${JSON.stringify(name)}: ${ordinal},`);
		}
		lines.push('\t},');
	}
	lines.push('}', '');
	return lines.join('\n');
}

writeFileSync(outFile, render());
